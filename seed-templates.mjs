async function seedTemplates() {
  console.log("🌱 Populando templates...\n");
  
  try {
    for (const template of templates) {
      console.log(`✅ Criando template: ${template.name}`);
      await db.insert(projectTemplates).values(template);
    }
    
    console.log(`\n🎉 ${templates.length} templates criados com sucesso!`);
    process.exit(0);
  } catch (error) {
    console.error("❌ Erro ao criar templates:", error);
    process.exit(1);
  }
}

