CREATE TABLE `inspirationProjects` (
	`id` int AUTO_INCREMENT NOT NULL,
	`name` varchar(255) NOT NULL,
	`location` text NOT NULL,
	`description` text,
	`concept` text,
	`area` int,
	`storeCount` int,
	`parkingSpaces` int,
	`floors` int,
	`year` int,
	`architect` text,
	`developer` text,
	`anchors` text,
	`features` text,
	`category` enum('strip_mall','open_mall','shopping_center','neighborhood_center') NOT NULL,
	`segment` enum('popular','medio','alto_padrao') NOT NULL DEFAULT 'medio',
	`latitude` varchar(50),
	`longitude` varchar(50),
	`images` text,
	`mainImageUrl` text,
	`createdAt` timestamp NOT NULL DEFAULT (now()),
	`updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `inspirationProjects_id` PRIMARY KEY(`id`)
);
