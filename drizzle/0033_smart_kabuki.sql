CREATE TABLE `exampleProjects` (
	`id` int AUTO_INCREMENT NOT NULL,
	`name` varchar(255) NOT NULL,
	`description` text NOT NULL,
	`category` varchar(100) NOT NULL,
	`landArea` decimal(10,2) NOT NULL,
	`occupancyRate` decimal(5,2) NOT NULL,
	`utilizationCoefficient` decimal(5,2) NOT NULL,
	`frontSetback` decimal(5,2) NOT NULL,
	`sideSetback` decimal(5,2) NOT NULL,
	`backSetback` decimal(5,2) NOT NULL,
	`dnaBuildingShape` text NOT NULL,
	`dnaFloors` int NOT NULL,
	`dnaRoofType` text NOT NULL,
	`dnaStyle` text NOT NULL,
	`dnaFeatures` text NOT NULL,
	`dnaPrimaryColor` varchar(7) NOT NULL,
	`dnaAccentColor` varchar(7) NOT NULL,
	`dnaMaterials` text NOT NULL,
	`dnaLandscaping` text NOT NULL,
	`dnaLayout` text NOT NULL,
	`dnaContext` text NOT NULL,
	`builtArea` decimal(10,2) NOT NULL,
	`numberOfStores` int NOT NULL,
	`parkingSpaces` int NOT NULL,
	`conceptualImageUrl` text,
	`floorplanImageUrl` text,
	`sectionImageUrl` text,
	`thumbnailUrl` text NOT NULL,
	`consistencyScore` int NOT NULL,
	`featured` tinyint NOT NULL DEFAULT 0,
	`viewCount` int NOT NULL DEFAULT 0,
	`duplicateCount` int NOT NULL DEFAULT 0,
	`createdAt` timestamp NOT NULL DEFAULT (now()),
	`updatedAt` timestamp NOT NULL DEFAULT (now()) ON UPDATE CURRENT_TIMESTAMP,
	CONSTRAINT `exampleProjects_id` PRIMARY KEY(`id`)
);
